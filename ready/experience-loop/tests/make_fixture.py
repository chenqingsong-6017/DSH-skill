def build(dest, style="num"):
    files = MOUNT_FILES if style == "mount" else FILES
    for rel, text in files.items():
        p = os.path.join(dest, rel.replace("/", os.sep))
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
    print("夹具已展开：%s（%d 个文件，style=%s）" % (dest, len(files), style))


def clean(dest):
    """安全清理：只删 basename 含 `.exp-loop-fixture` 的目录。"""
    if DEFAULT_NAME not in os.path.basename(os.path.normpath(dest)):
        print("拒绝清理（目标目录名不含 %s，防误删）：%s" % (DEFAULT_NAME, dest), file=sys.stderr)
        return 2
    if not os.path.exists(dest):
        print("无需清理（不存在）：%s" % dest)
        return 0
    shutil.rmtree(dest)
    print("夹具已清理：%s" % dest)
    return 0


def main():
    ap = argparse.ArgumentParser(description="展开/清理 experience-loop 回归夹具")
    ap.add_argument("--dest", help="展开位置；默认 <当前目录>/%s" % DEFAULT_NAME)
    ap.add_argument("--style", choices=("num", "mount"), default="num",
                    help="夹具制式：num＝编号制（默认）；mount＝挂载制（描述性卡名，3.4.0）")
    ap.add_argument("--clean", action="store_true", help="清理夹具目录")
    args = ap.parse_args()
    dest = args.dest or os.path.join(os.getcwd(), DEFAULT_NAME)
    return clean(dest) if args.clean else (build(dest, args.style) or 0)


if __name__ == "__main__":
    sys.exit(main())
